#!/usr/bin/env python
"""Regenerate the static hatch-pattern JS asset.

The Dyson hatch tile is global and deterministic (seed=0), so it
ships as a base64 SVG data URI baked into a committed JS module
instead of a server endpoint. Run via ``make hatch-pattern``
whenever ``render_hatch_svg`` changes (rare).

SVG (not PNG): the patch is 512x512 of high-entropy vector
hatching — the SVG gzips to ~41 KB while a rasterised PNG is
~256 KB on the wire and won't compress. Pipeline:
``render_hatch_svg(0)`` -> base64 -> ``data:image/svg+xml`` ->
``nhc/web/static/js/hatch_pattern.js``.
"""

from __future__ import annotations

import base64
import pathlib

from nhc.rendering.svg import render_hatch_svg

_OUT = (
    pathlib.Path(__file__).resolve().parents[1]
    / "nhc" / "web" / "static" / "js" / "hatch_pattern.js"
)

_TEMPLATE = """\
// Generated by `make hatch-pattern` — do not edit by hand.
//
// Static seed=0 Dyson hatch tile: render_hatch_svg(0) embedded as
// a base64 SVG data URI. Replaces the old /api/hatch.svg endpoint
// — the tile never varies, so there is no reason to render or
// fetch it per game. SVG (not PNG) keeps the gzipped payload
// ~41 KB; the client feeds this straight to Image.src as before.
window.NHC_HATCH_URI = "data:image/svg+xml;base64,{b64}";
"""


def main() -> None:
    svg = render_hatch_svg(seed=0)
    b64 = base64.b64encode(svg.encode("utf-8")).decode("ascii")
    _OUT.write_text(_TEMPLATE.format(b64=b64), encoding="utf-8")
    print(
        f"wrote {_OUT.relative_to(_OUT.parents[4])} "
        f"({len(svg)} svg bytes, {len(b64)} b64 chars)"
    )


if __name__ == "__main__":
    main()
